export const getTranslation = (
  langCode: string,
  key: string,
  fallback?: string
): string => {
  const dict = translations[langCode] || translations.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return fallback || key;
};

// React Context for Global App Language
export interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  t: (key: string, fallback?: string) => string;
  dir: "ltr" | "rtl";
  currentLanguageObj: Language;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "en",
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key,
  dir: "ltr",
  currentLanguageObj: SUPPORTED_LANGUAGES[0],
});

export { translateTextTo } from "./translationEngine";

export const LanguageProvider: React.FC<{
  children: ReactNode;
  initialLanguage?: string;
  onLanguageChange?: (lang: string) => void;
}> = ({ children, initialLanguage, onLanguageChange }) => {
  const [language, setLangState] = useState<string>(() => {
    return (
      initialLanguage ||
      (typeof localStorage !== "undefined"
        ? localStorage.getItem("studymate_language") || "en"
        : "en")
    );
  });

  const handleSetLanguage = (newLang: string) => {
    setLangState(newLang);
    if (typeof localStorage !== "undefined") {
      localStorage.setItem("studymate_language", newLang);
    }
    const langObj = SUPPORTED_LANGUAGES.find((l) => l.code === newLang);
    if (typeof document !== "undefined") {
      document.documentElement.lang = newLang;
      document.documentElement.dir = langObj?.dir || "ltr";
    }
    domTranslator.setLanguage(newLang);
    if (onLanguageChange) {
      onLanguageChange(newLang);
    }
  };

  useEffect(() => {
    if (initialLanguage && initialLanguage !== language) {
      handleSetLanguage(initialLanguage);
    }
  }, [initialLanguage]);

  useEffect(() => {
    const langObj = SUPPORTED_LANGUAGES.find((l) => l.code === language);
    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
      document.documentElement.dir = langObj?.dir || "ltr";
    }
    domTranslator.init(language);
  }, [language]);

  const t = (key: string, fallback?: string): string => {
    return getTranslation(language, key, fallback);
  };

  const currentLanguageObj =
    SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage: handleSetLanguage,
        t,
        dir: currentLanguageObj.dir,
        currentLanguageObj,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

